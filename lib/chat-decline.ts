/**
 * 「答えられなかった」返答の文言と、その見分け方。
 *
 * 管理画面（/admin/chat-logs）で「答えられていない質問」を拾うために要る。
 *
 * ⚠ 知識の引き方（retrieval）では判定できない。実測（2026-09-22）:
 *   - 料金 … ピン留めの知識で答えられたが、類似検索は0件なので no_match
 *   - 犬の散歩 … 見当違いの知識が閾値を超えて matched だが、答えは「分かりかねます」
 *   つまり retrieval は「検索がどう動いたか」であって「答えられたか」ではない。
 *   答えられたかどうかは、返答そのものを見るしかない。
 *
 * ⚠ クライアント側（管理画面）からも読むので、このファイルにサーバー専用のものを import しない。
 */

/** 知識に無いことを聞かれたときに、モデルに言わせる文（system プロンプトに埋める） */
export const DECLINE_SENTENCE = 'こちらでは分かりかねます'

/**
 * この返答は「答えられなかった」ものか。
 *
 * ⚠ 「かねます」だけで見ない。「返金はいたしかねます」は答えている文なので、
 *   それまで未回答に数えると、拾いたい質問が埋もれる。
 *   拾うのは「分かりかねる／答えかねる」と言っている形だけ。
 */
export function isDeclineReply(text: string): boolean {
  return /(分|わ)かりかね|お?答えい?たしかね|お?答えしかね|回答(いた)?しかね/.test(text)
}
